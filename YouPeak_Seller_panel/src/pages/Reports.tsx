import { TrendingUp, ShoppingCart, Package, Warehouse, Users, Percent, Wallet, RotateCcw, FileText, Download, Eye } from "lucide-react";
import { reports, recentExports } from "@/data/mockData";
import { PageHeader, SearchInput, Button, Card, useToast } from "@/components/ui";
import { useState } from "react";

const iconMap: Record<string, React.ElementType> = {
  TrendingUp, ShoppingCart, Package, Warehouse, Users, Percent, Wallet, RotateCcw, FileText
};

export default function Reports() {
  const [search, setSearch] = useState("");
  const { show, ToastEl } = useToast();

  const filtered = reports.filter((r) =>
    !search || r.name.toLowerCase().includes(search.toLowerCase())
  );

  return (
    <div className="space-y-5">
      {ToastEl}
      <PageHeader title="Reports" subtitle="Generate and download business reports"
        actions={
          <>
            <select className="h-8 px-2 text-xs border border-[#E5E9E8] rounded-md bg-white text-[#64748B]">
              <option>27 Aug - 27 Aug 2026</option>
            </select>
            <select className="h-8 px-2 text-xs border border-[#E5E9E8] rounded-md bg-white text-[#64748B]">
              <option>Report Type: All Reports</option>
            </select>
          </>
        }
      />

      <div className="flex gap-3">
        <SearchInput value={search} onChange={setSearch} placeholder="Search reports..." />
      </div>

      {/* Report Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
        {filtered.map((r) => {
          const Icon = iconMap[r.icon] || FileText;
          return (
            <Card key={r.id} className="hover:border-[#16A34A] transition-colors cursor-pointer">
              <div className="flex items-start gap-3">
                <div className="w-10 h-10 rounded-lg bg-green-50 flex items-center justify-center shrink-0">
                  <Icon size={20} className="text-[#16A34A]" />
                </div>
                <div className="flex-1 min-w-0">
                  <p className="text-sm font-semibold text-[#10252E]">{r.name}</p>
                  <p className="text-xs text-[#64748B] mt-0.5">{r.description}</p>
                  <p className="text-[10px] text-[#64748B] mt-1">Generated on: 27 Aug 2026</p>
                </div>
              </div>
              <div className="flex gap-2 mt-4 pt-3 border-t border-[#E5E9E8]">
                <Button variant="secondary" size="sm" icon={<Eye size={12} />} className="flex-1" onClick={() => show(`Opening ${r.name}...`, "info")}>View</Button>
                <Button variant="primary" size="sm" icon={<Download size={12} />} className="flex-1" onClick={() => show(`Downloading ${r.name}...`, "success")}>Download</Button>
              </div>
            </Card>
          );
        })}
      </div>

      {/* Recent Exports */}
      <Card padding={false}>
        <div className="px-5 py-3.5 border-b border-[#E5E9E8]">
          <h3 className="text-sm font-semibold text-[#10252E]">Recent Exports</h3>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead><tr className="border-b border-[#E5E9E8]">
              {["Report Name", "Date Range", "Format", "Generated Date", "Generated By", "Download"].map((h) => (
                <th key={h} className="px-4 py-2.5 text-left text-xs font-medium text-[#64748B] whitespace-nowrap">{h}</th>
              ))}
            </tr></thead>
            <tbody className="divide-y divide-[#E5E9E8]">
              {recentExports.map((e, i) => (
                <tr key={i} className="hover:bg-[#F5F7F6] transition-colors">
                  <td className="px-4 py-3 text-xs font-medium text-[#10252E]">{e.name}</td>
                  <td className="px-4 py-3 text-xs text-[#64748B]">{e.dateRange}</td>
                  <td className="px-4 py-3">
                    <span className="px-2 py-0.5 bg-blue-50 text-blue-700 text-[10px] rounded font-medium">{e.format}</span>
                  </td>
                  <td className="px-4 py-3 text-xs text-[#64748B]">{e.generatedDate}</td>
                  <td className="px-4 py-3 text-xs text-[#64748B]">{e.generatedBy}</td>
                  <td className="px-4 py-3">
                    <Button variant="ghost" size="sm" icon={<Download size={12} />} onClick={() => show("Downloading...", "success")}>Download</Button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>
    </div>
  );
}
